export function getCountryForTimezone(tz) {
    for (var country in countryTimezones) {
        if (countryTimezones[country].indexOf(tz) !== -1) {
            return country;
        }
    }
    return null;
}

export function getDisplayLabel(tz) {
    var country = getCountryForTimezone(tz);
    var zone = tzDisplayNames[tz] || tz.split('/').pop().replace(/_/g, ' ');
    if (country) {
        return country + ' - ' + zone;
    }
    return tz;
}

