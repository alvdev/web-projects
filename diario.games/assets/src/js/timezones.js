export function normalize(str) {
    return str.toLowerCase().replace(/[à-üÀ-Ü]/g, function (c) { return accentMap[c] || c; });
}

export function findCityMatch(query) {
    var q = normalize(query).trim();
    if (!q) return null;

    if (cityTimezones[q]) return cityTimezones[q];

    var keys = Object.keys(cityTimezones);
    for (var i = 0; i < keys.length; i++) {
        if (keys[i].indexOf(q) === 0) return cityTimezones[keys[i]];
    }
    for (var j = 0; j < keys.length; j++) {
        if (keys[j].indexOf(q) !== -1) return cityTimezones[keys[j]];
    }
    return null;
}

export function findCountryMatch(query) {
    var q = normalize(query).trim();
    if (!q) return null;

    if (countryTimezones[q]) return countryTimezones[q];

    var keys = Object.keys(countryTimezones);
    for (var i = 0; i < keys.length; i++) {
        var normalizedKey = normalize(keys[i]);
        if (normalizedKey.indexOf(q) === 0) return countryTimezones[keys[i]];
    }
    for (var j = 0; j < keys.length; j++) {
        var normalizedKey2 = normalize(keys[j]);
        if (normalizedKey2.indexOf(q) !== -1) return countryTimezones[keys[j]];
    }
    return null;
}

export function isValidTimezone(tz) {
    if (tz === 'UTC') return true;
    try {
        Intl.DateTimeFormat('en', { timeZone: tz });
        return true;
    } catch (e) {
        return false;
    }
}

export function getUtcOffset(tz) {
    if (tz === 'UTC') return '+00:00';
    var date = new Date();
    try {
        var formatter = new Intl.DateTimeFormat('en-US', { timeZone: tz, timeZoneName: 'shortOffset' });
        var parts = formatter.formatToParts(date);
        for (var i = 0; i < parts.length; i++) {
            if (parts[i].type === 'timeZoneName') {
                return parts[i].value.replace('GMT', '');
            }
        }
    } catch (e) {}
    return '+00:00';
}
